const root = new URL("../", import.meta.url)
const outFile = fileURLToPath(new URL("components/icon-data.ts", root))
const pkgDir = new URL("node_modules/@phosphor-icons/react/", root)
const { version } = JSON.parse(
	readFileSync(new URL("package.json", pkgDir), "utf8"),
)

/** Flatten a duotone Fragment into [tag, attributes] pairs. */
function shapesOf(name, element) {
	const children = [element.props.children].flat()
	return children.map((child) => {
		if (typeof child?.type !== "string") {
			throw new Error(`${name}: expected SVG elements, got ${String(child)}`)
		}
		const { children: nested, ...attrs } = child.props
		if (nested !== undefined) {
			throw new Error(
				`${name}: nested <${child.type}> children are not supported`,
			)
		}
		return [child.type, attrs]
	})
}

const entries = []
for (const name of icons) {
	const weights = (
		await import(
			pathToFileURL(fileURLToPath(new URL(`dist/defs/${name}.es.js`, pkgDir)))
				.href
		)
	).default
	const duotone = weights.get("duotone")
	if (!duotone)
		throw new Error(`${name}: no duotone weight in @phosphor-icons/react`)
	entries.push(`\t${name}: ${JSON.stringify(shapesOf(name, duotone))},`)
}

const source = `/*
 * Generated by scripts/generate-icon-data.mjs from @phosphor-icons/react
 * ${version}. Do not edit by hand: add the icon name there and re-run it.
 */
export type IconShape = readonly [tag: string, attributes: Record<string, string>]

export const duotoneIcons = {
${entries.join("\n")}
} satisfies Record<string, readonly IconShape[]>

export type DuotoneIconName = keyof typeof duotoneIcons
`

const formatted = await format(source, {
	...(await resolveConfig(outFile, { editorconfig: true })),
	filepath: outFile,
})

if (process.argv.includes("--check")) {
	let current = ""
	try {
		current = readFileSync(outFile, "utf8")
	} catch {}
	if (current !== formatted) {
		console.error(
			"components/icon-data.ts is out of date. Run: node scripts/generate-icon-data.mjs",
		)
		process.exit(1)
	}
	console.log(`Icon data is current: ${icons.length} duotone icons.`)
} else {
	writeFileSync(outFile, formatted)
	console.log(`Wrote ${icons.length} duotone icons to components/icon-data.ts`)
}
