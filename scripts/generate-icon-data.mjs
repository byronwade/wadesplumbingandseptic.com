/*
 * Writes components/icon-data.ts: the duotone SVG shapes for every Phosphor
 * icon the site uses, copied from the installed @phosphor-icons/react.
 *
 * Each Phosphor icon module carries all six weights (bold, duotone, fill,
 * light, regular, thin), so importing it ships five unused sets of paths to
 * every page that renders an icon from a client component. The site only
 * ever draws duotone, so components/icons.tsx renders from this file instead.
 *
 * To add an icon, add its Phosphor name to `icons` and run:
 *   node scripts/generate-icon-data.mjs
 * `--check` exits non-zero when the committed file is out of date (CI).
 */
