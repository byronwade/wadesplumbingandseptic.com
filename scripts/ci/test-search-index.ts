import assert from "node:assert/strict"
import Module from "node:module"

// Exercise the real inventory under tsx without a Next server runtime.
const runtime = Module as typeof Module & {
	_load: (
		request: string,
		parent: NodeModule | null,
		isMain: boolean,
	) => unknown
}
const load = runtime._load
runtime._load = function (request, parent, isMain) {
	if (request === "server-only") return {}
	if (request === "next/cache") return { cacheLife() {}, cacheTag() {} }
	return load(request, parent, isMain)
}

async function main() {
	const { getSearchIndex } = await import("../../lib/search-index")
	const { searchDocuments } = await import("../../lib/search")
	const { default: config } = await import("../../next.config")
	const index = await getSearchIndex()
	const paths = new Set(index.map(({ href }) => href))
	let passed = 0
	function check(condition: boolean, message: string) {
		assert.ok(condition, message)
		passed++
	}

	check(
		!paths.has("/engineered-septic-systems-santa-cruz-county"),
		"Retired engineered septic landing page must not appear in search",
	)
	for (const redirect of (await config.redirects?.()) ?? []) {
		// Parameterized legacy routes are not generated by the search inventory.
		if (redirect.source.includes(":")) continue
		check(
			!paths.has(redirect.source),
			`Redirect leaked into search: ${redirect.source}`,
		)
	}
	for (const path of [
		"/service-offerings/engineered-septic-system-installation",
		"/service-offerings/drain-cleaning",
		"/contact",
		"/services",
		"/expert-tips",
		"/service-area/aptos-ca-plumbing-septic-services",
		"/glossary",
	]) {
		check(
			paths.has(path),
			`Canonical destination must remain searchable: ${path}`,
		)
	}
	for (const slug of [
		"failed-septic-repair-replacement-santa-cruz-county",
		"plumbing-repair-services-santa-cruz-county",
		"water-main-sewer-line-repair-santa-cruz-county",
	]) {
		check(
			paths.has(`/${slug}`),
			`Live noindex ad page remains searchable: ${slug}`,
		)
	}
	for (const slug of ["thank-you", "contact-call-first"]) {
		check(!paths.has(`/${slug}`), `Utility page must stay excluded: ${slug}`)
	}
	check(paths.size === index.length, "Search URLs must remain unique")
	check(
		index.some(({ href }) => href.startsWith("tel:")),
		"Call action remains available",
	)
	for (const query of [
		"engineered septic",
		"alternative septic",
		"septic installation",
	]) {
		const hits = searchDocuments(index, query, 12)
		check(
			hits.some(
				({ href }) =>
					href === "/service-offerings/engineered-septic-system-installation",
			),
			`Search must find the canonical engineered septic service for: ${query}`,
		)
	}
	console.log(
		`Search index checks: ${passed} passed, 0 failed (${index.length} documents)`,
	)
}

main().catch((error) => {
	console.error(error)
	process.exitCode = 1
})
