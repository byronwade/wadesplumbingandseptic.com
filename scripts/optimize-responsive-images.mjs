/**
 * Build mobile-width WebP/AVIF siblings for large local photos.
 *
 * next/image is unoptimized on this host, so `sizes` and `quality` do not
 * resize files. Phones were downloading 1200px+ heroes for ~370px boxes.
 * This writes `-828.webp` / `-828.avif` (and a matching full-size `.avif`
 * when one is missing) and a mapping module the UI imports.
 */
import {
	existsSync,
	mkdirSync,
	renameSync,
	statSync,
	unlinkSync,
	writeFileSync,
} from "node:fs"
import { dirname, join, relative } from "node:path"
import { fileURLToPath } from "node:url"

import sharp from "sharp"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const publicRoot = join(root, "public")
const dirs = [
	"images/work",
	"images/locations",
	"images/team",
	"images/services",
]

const NARROW_WIDTH = 828
const SKIP_NAME = /(?:-828|hero-mobile|hero-desktop|hero-portrait|mark-sm)$/

const avif = {}
const narrow = {}

async function processFile(absPath) {
	const rel = relative(publicRoot, absPath).replaceAll("\\", "/")
	const publicPath = `/${rel}`
	const parsed = rel.match(/^(.*)\.webp$/)
	if (!parsed) return
	const stem = parsed[1]
	const baseName = stem.split("/").at(-1)
	if (SKIP_NAME.test(baseName)) return

	const image = sharp(absPath)
	const meta = await image.metadata()
	const width = meta.width ?? 0
	const height = meta.height ?? 0
	if (width < 2 || height < 2) return

	const avifPath = join(publicRoot, `${stem}.avif`)
	const avifPublic = `/${stem}.avif`
	if (rel.endsWith(".webp")) {
		try {
			const tmp = `${avifPath}.tmp`
			await sharp(absPath).avif({ quality: 48, effort: 6 }).toFile(tmp)
			if (
				!existsSync(avifPath) ||
				statSync(tmp).size < statSync(avifPath).size
			) {
				renameSync(tmp, avifPath)
			} else {
				unlinkSync(tmp)
			}
			if (existsSync(avifPath)) avif[publicPath] = avifPublic
		} catch (error) {
			console.warn(`avif failed for ${publicPath}:`, error.message)
		}
	}

	if (width > NARROW_WIDTH) {
		const narrowStem = `${stem}-828`
		const narrowWebpPath = join(publicRoot, `${narrowStem}.webp`)
		const narrowAvifPath = join(publicRoot, `${narrowStem}.avif`)
		const resized = sharp(absPath).resize({
			width: NARROW_WIDTH,
			withoutEnlargement: true,
		})
		await resized
			.clone()
			.webp({ quality: 60, effort: 6 })
			.toFile(narrowWebpPath)
		await resized
			.clone()
			.avif({ quality: 45, effort: 6 })
			.toFile(narrowAvifPath)
		narrow[publicPath] = `/${narrowStem}.webp`
		avif[`/${narrowStem}.webp`] = `/${narrowStem}.avif`
	}
}

const { glob } = await import("node:fs/promises")
for (const dir of dirs) {
	for await (const entry of glob("**/*.webp", {
		cwd: join(publicRoot, dir),
	})) {
		await processFile(join(publicRoot, dir, entry))
	}
}

const out = join(root, "lib/image-variants.generated.ts")
mkdirSync(dirname(out), { recursive: true })
const serialize = (obj) =>
	Object.entries(obj)
		.sort(([a], [b]) => a.localeCompare(b))
		.map(([from, to]) => `\t${JSON.stringify(from)}: ${JSON.stringify(to)},`)
		.join("\n")

writeFileSync(
	out,
	`/* Generated by scripts/optimize-responsive-images.mjs. Do not edit. */\n` +
		`export const imageAvif = {\n${serialize(avif)}\n} as const\n\n` +
		`export const imageNarrow = {\n${serialize(narrow)}\n} as const\n`,
)

console.log(
	`wrote ${Object.keys(avif).length} avif maps and ${Object.keys(narrow).length} narrow maps to ${relative(root, out)}`,
)
